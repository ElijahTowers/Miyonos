const char* BitmapFont::glyph(char character) const {
  const char upper =
      static_cast<char>(std::toupper(static_cast<unsigned char>(character)));
  for (const auto& item : kGlyphs) {
    if (item.character == upper) return item.rows;
  }
  return "11111100010001000100000000010000100";
}

int BitmapFont::width(const std::string& text, int scale) const {
  return text.empty() ? 0 : static_cast<int>(text.size()) * 6 * scale - scale;
}

void BitmapFont::draw(const std::string& text, int x, int y, int scale,
                      SDL_Color color, int max_width) const {
  SDL_SetRenderDrawColor(renderer_, color.r, color.g, color.b, color.a);
  const int origin = x;
  for (char character : text) {
    if (max_width >= 0 && x + 5 * scale > origin + max_width) break;
    const char* bits = glyph(character);
    for (int row = 0; row < 7; ++row) {
      for (int column = 0; column < 5; ++column) {
        if (bits[row * 5 + column] == '1') {
          SDL_Rect pixel{x + column * scale, y + row * scale, scale, scale};
          SDL_RenderFillRect(renderer_, &pixel);
        }
      }
    }
    x += 6 * scale;
  }
}

void BitmapFont::draw_centered(const std::string& text, int y, int scale,
                               SDL_Color color, int center_x) const {
  draw(text, center_x - width(text, scale) / 2, y, scale, color);
}

